sbmk "void wait_line(void)"
## FUNCTION :: wait_line
##      RETURN TYPE = VOID
##      PARAMETERS: <NONE>
##
##      REGISTERS DESTROYED:
##          a0, a1, t0
##
## Reads a line of input from the keyboard.
## Stores the input into `inp` as a null-terminated string.
wait_line:
    mov a0, rdy_prompt
    cal puts

    mov t0, 0
    cea inp, 0, 1
.wait:
    yield               # Keep the watchdog happy
    syscall SYS_GET_KEYBOARD_INPUT
    cmp eq, a0, 0
    jtr .wait

    psh a1
    and a1, 1           # Ensure key is being pressed, not released
    cmp eq, a1, 0
    pop a1
    jtr .wait

    psh a1
    and a1, 8
    cmp eq, a1, 0
    pop a1
    jtr .no_shift

    # SHIFT key is pressed. Do some checks for shifted chars
    cmp eq, a0, '9'
    jfs .not_nine
    mov a0, '('
    jmp .no_shift

.not_nine:
    cmp eq, a0, '0'
    mov a0, ')'
    jmp .no_shift

.no_shift:
    cmp eq, a0, KEY_ENTER
    jfs .no_enter

    mov a0, 0x0a
    psh ea
    psh a0
    vpsh t0..t4
    cal putch
    vpop t0..t4
    pop a0
    pop ea

    jtr .done

.no_enter:
    cmp eq, a0, KEY_BACKSPACE
    jfs .after_special

    # BACKSPACE key is pressed.
    dec t0
    ste u8t, t0, 0

    psh ea
    psh a0
    vpsh t0..t4
    cal putch
    vpop t0..t4
    pop a0
    pop ea

.after_special:
    psh a0              # Ignore other special keys
    and a0, 128
    cmp eq, a0, 0
    pop a0
    jfs .wait

    ste u8t, t0, a0

    psh ea
    psh a0
    vpsh t0..t4
    cal putch
    vpop t0..t4
    pop a0
    pop ea

    inc t0
    jmp .wait

.done:
    ste u8t, t0, 0
    ret


