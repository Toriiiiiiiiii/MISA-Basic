sbmk "void putch(u8t ch)"
## FUNCTION :: putch
##      RETURN TYPE = VOID
##      PARAMETERS:
##          u8t ch :: Char to print out
##
##      REGISTERS DESTROYED:
##          t0, t1, ea
##
##  Outputs a character to the display.
putch:
    cmp eq, a0, 0x0a
    jfs .no_newln

    mov t0, 0
    str u16t, cursorx, t0

    lod u16t, t0, cursory
    inc t0
    str u16t, cursory, t0
    ret

.no_newln:
    lod u16t, t0, cursorx
    lod u16t, t1, cursory
    mul t1, 320/4
    add t0, t1

    cea vmem, t0, 1
    ste u8t, 0, a0

    lod u16t, t0, cursorx
    inc t0
    cmp eq, t0, 80
    jfs .noline

    mov t0, 0
    lod u16t, t1, cursory
    inc t1
    str u16t, cursory, t0

.noline:
    str u16t, cursorx, t0
    ret

sbmk "void puts(char *s)"
## FUNCTION :: puts
##      RETURN TYPE = VOID
##      PARAMETERS:
##          u8t *str :: Pointer to the string
##
##      REGISTERS DESTROYED:
##          ea, a0, t0
##
## Outputs a string to the display using putch
puts:
    cea a0, 0, 1
    mov t0, 0
.loop:
    lde u8t, a0, 0

    cmp eq, a0, 0
    jtr .done

    psh ea
    psh t0
    psh t1
    cal putch
    pop t1
    pop t0
    pop ea

    inc t0
    inc ea
    jmp .loop
.done:
    ret


sbmk "void draw_vmem(void)"
## FUNCTION :: draw_vmem
##      RETURN TYPE = VOID
##      PARAMETERS:
##          void
##
##      REGISTERS DESTROYED:
##          t0, t1, t2, t3, ea, a0, a1, a2, a3
##
## Renders the text display to the screen
draw_vmem:
    mov t0, 0
    mov t1, 0
.loop:
    mov t2, t1
    mul t2, 80
    add t2, t0

    # t2 = vmem offset
    cea vmem, t2, 1
    lde u8t, t3, 0

    # t3 = character
    cmp eq, t3, 0x0a
    jfs .no_newln

    mov t0, 0
    inc t1
    jmp .loop

.no_newln:
    cmp gte, t3, 0x20
    jtr .printchr

    mov t3, 0x20

.printchr:
    sub t3, 0x20
    mul t3, 36

    mov a0, font
    add a0, t3

    mov a1, t0
    mul a1, 4
    mov a2, t1
    mul a2, 8
    mov a3, 0
    syscall SYS_DRAW_TEXTURE

.noprint:
    inc t0
    cmp eq, t0, 80
    jfs .noline

    mov t0, 0
    inc t1

    cmp eq, t1, 30
    jtr .done

.noline:
    jmp .loop

.done:
    ret


